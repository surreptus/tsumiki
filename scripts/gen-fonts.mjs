// Writes src/styles/fonts.css: the Fontsource @font-face rules the site actually needs.
// Fontsource ships about 120 unicode-range subsets per weight of Zen Maru Gothic, each with a woff
// fallback, and including all of them put about 290 KB of @font-face text into every page's CSS.
// This keeps only the subsets that cover a character used somewhere in src/, and only the woff2
// source (every browser that supports unicode-range supports woff2). Runs before dev and build.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const out = join(root, 'src/styles/fonts.css');
const sources = [
  '@fontsource/zen-maru-gothic/400.css',
  '@fontsource/zen-maru-gothic/700.css',
  '@fontsource/jetbrains-mono/latin-400.css',
  '@fontsource/jetbrains-mono/latin-700.css',
];

// Every code point used in the site's source, plus printable ASCII and Latin-1 for UI strings.
const used = new Set();
for (let c = 0x20; c <= 0xff; c++) used.add(c);
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(mdx?|json|astro|tsx?|mjs|css)$/.test(name)) {
      for (const ch of readFileSync(path, 'utf8')) used.add(ch.codePointAt(0));
    }
  }
};
walk(join(root, 'src'));

const covers = (range) =>
  range.split(',').some((part) => {
    const [lo, hi = lo] = part.trim().replace(/^U\+/i, '').split('-');
    const a = parseInt(lo, 16);
    const b = parseInt(hi, 16);
    for (const c of used) if (c >= a && c <= b) return true;
    return false;
  });

let kept = 0;
let total = 0;
const blocks = [];
for (const src of sources) {
  const path = join(root, 'node_modules', src);
  const dir = relative(join(root, 'src/styles'), join(path, '..'));
  for (const rule of readFileSync(path, 'utf8').match(/@font-face\s*{[^}]*}/g) ?? []) {
    total++;
    const range = rule.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (range && !covers(range)) continue;
    kept++;
    blocks.push(
      rule
        .replace(/src:[^;]+;/, (s) => {
          const woff2 = s.match(/url\(\.\/([^)]+\.woff2)\)/)[1];
          return `src: url(${dir}/${woff2}) format('woff2');`;
        })
        .replace(/\n\s*/g, ' '),
    );
  }
}

writeFileSync(
  out,
  `/* Generated by scripts/gen-fonts.mjs from Fontsource. Do not edit; run \`node scripts/gen-fonts.mjs\`. */\n${blocks.join('\n')}\n`,
);
console.log(`fonts.css: kept ${kept} of ${total} @font-face rules`);
